import assert from "node:assert/strict";
import { chromium } from "playwright-core";
const b = await chromium.launch({ channel: "chrome", headless: true });
const errores = [];
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
await ctx.route(/\/api\//, (r) => r.fulfill({ json: { disponible: false, conectado: false, resultados: [] } }));
await ctx.addInitScript(() => { localStorage.setItem("comidas-bienvenida", "vista"); window.__recetaJuan = true; });
const p = await ctx.newPage();
p.on("pageerror", (e) => errores.push(e.message));
await p.goto("http://localhost:5199");
await p.waitForTimeout(1500);
await p.getByRole("button", { name: "Grupo", exact: true }).locator("visible=true").first().click();
await p.waitForTimeout(600);
await p.getByRole("tab", { name: "Imágenes" }).click();
await p.waitForTimeout(500);
await p.getByRole("button", { name: /^Desayuno/ }).click();
await p.waitForTimeout(800);
const tarjeta = p.locator(".comida", { hasText: "Yogur con granola" });
await tarjeta.getByRole("button", { name: "Ver alimentos" }).click();
await p.waitForTimeout(500);
const receta = tarjeta.locator(".detalle-receta");
assert.match(await receta.innerText(), /Receta · de Juan\s*Ver receta/);
await tarjeta.screenshot({ path: "capturas/receta-desglose.png" });
await receta.getByRole("button", { name: /Ver receta/ }).click();
await p.waitForTimeout(900);
assert.match(await p.locator(".volver-ajustes h1").innerText(), /mis recetas/i);
await p.getByRole("dialog").filter({ hasText: "Budín de banana" }).waitFor();
await p.waitForTimeout(500);
await p.screenshot({ path: "capturas/receta-abierta.png" });
assert.deepEqual(errores, []);
await b.close();
console.log("link a la receta: pruebas pasadas");
