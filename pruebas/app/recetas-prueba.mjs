import assert from "node:assert/strict";
import { chromium } from "playwright-core";
const b = await chromium.launch({ channel: "chrome", headless: true });
const errores = [];
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
await ctx.route(/\/api\//, (r) => r.fulfill({ json: { disponible: false, conectado: false, resultados: [] } }));
await ctx.addInitScript(() => { window.__plan = true; localStorage.setItem("comidas-bienvenida", "vista"); });
const p = await ctx.newPage();
p.on("pageerror", (e) => errores.push(e.message));
await p.goto("http://localhost:5199/?vista=ajustes");
await p.waitForTimeout(1200);
await p.locator(".menu-ajustes button", { hasText: "Mis recetas" }).click();
await p.waitForTimeout(400);
await p.getByRole("button", { name: "Nueva receta" }).click();
await p.waitForTimeout(500);
await p.getByLabel("Nombre de la receta").fill("Budín de banana");
await p.getByLabel("Porciones", { exact: true }).fill("8");
const sumarIngrediente = async (q, nombre) => {
  await p.getByLabel("Buscar ingrediente").fill(q);
  await p.waitForTimeout(300);
  await p.locator(".editor-receta .resultados button", { hasText: nombre }).first().click();
  await p.waitForTimeout(250);
};
await sumarIngrediente("harina", "Harina de trigo");
await p.getByLabel("Medida de Harina de trigo").selectOption({ label: "gramos" });
await p.getByLabel("Cantidad de Harina de trigo").fill("250");
await sumarIngrediente("banana", "Banana");
await p.getByLabel("Cantidad de Banana").fill("3");
await sumarIngrediente("huevo", "Huevo");
await p.getByLabel("Cantidad de Huevo").fill("2");
await sumarIngrediente("azucar", "Azúcar");
await p.getByLabel("Medida de Azúcar").selectOption({ label: "gramos" });
await p.getByLabel("Cantidad de Azúcar").fill("150");
await p.getByLabel("Peso de la receta terminada").fill("800");
await p.waitForTimeout(300);
const resumen = await p.locator(".resumen-receta").innerText();
console.log("resumen:", resumen.replace(/\n/g, " | "));
// harina 250 g = 910, banana 360 g = 320, huevo 100 g = 143, azúcar 150 g = 600 → 1973 kcal, 8 porciones de 100 g = 247 kcal
assert.ok(resumen.includes("1.973 kcal") && resumen.includes("(100 g)") && resumen.includes("247 kcal"), resumen);
await p.screenshot({ path: "capturas/receta-editor.png" });
await p.getByRole("button", { name: "Guardar receta" }).click();
await p.waitForTimeout(700);
const guardada = await p.evaluate(() => window.__db.recetas_propias[0]);
assert.equal(guardada.nombre, "Budín de banana");
assert.equal(guardada.porciones, 8);
assert.equal(guardada.ingredientes.length, 4);
assert.ok(!("medidas" in guardada.ingredientes[0]), "no guarda las medidas de la lista");
assert.equal(await p.locator(".lista-recetas li").count(), 1);
console.log("lista:", await p.locator(".lista-recetas li").innerText());
await p.screenshot({ path: "capturas/receta-lista.png" });
// Usarla al cargar una comida
await p.getByRole("button", { name: "Resumen", exact: true }).locator("visible=true").first().click();
await p.waitForTimeout(500);
await p.getByRole("button", { name: "Agregar merienda" }).click();
await p.waitForTimeout(600);
await p.getByLabel("Buscar alimento o producto").fill("budin");
await p.waitForTimeout(400);
const fila = p.getByRole("dialog").locator(".resultados button", { hasText: "Budín de banana" }).first();
console.log("en la búsqueda:", (await fila.innerText()).replace(/\n/g, " | "));
assert.ok((await fila.innerText()).includes("porción (1/8)"));
await fila.click();
await p.waitForTimeout(300);
const item = await p.getByRole("dialog").locator(".fila-item").first().innerText();
console.log("cargada:", item.replace(/\n/g, " | "));
assert.ok(item.includes("247 kcal"));
await p.screenshot({ path: "capturas/receta-usada.png" });
await b.close();
assert.deepEqual(errores, []);
console.log("recetas propias: pruebas pasadas");
