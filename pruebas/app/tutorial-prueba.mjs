import assert from "node:assert/strict";
import { chromium } from "playwright-core";
const b = await chromium.launch({ channel: "chrome", headless: true });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
await ctx.route(/\/api\//, (r) => r.fulfill({ json: { disponible: false, conectado: false, resultados: [] } }));
await ctx.addInitScript(() => { window.__plan = true; localStorage.setItem("comidas-bienvenida", "vista"); });
const p = await ctx.newPage();
const errores = [];
p.on("pageerror", (e) => errores.push(e.message));
await p.goto("http://localhost:5199/?vista=ajustes");
await p.waitForTimeout(1200);
await p.locator(".menu-ajustes button", { hasText: "Tutorial" }).click();
await p.waitForTimeout(400);
await p.locator(".tutorial-seccion > summary", { hasText: "Apple Salud y WHOOP" }).click();
await p.locator(".tutorial-pregunta > summary", { hasText: "paso a paso" }).click();
const abierta = p.locator(".tutorial-pregunta[open] .tutorial-pasos").first();
await abierta.scrollIntoViewIfNeeded();
const pasos = await abierta.locator("li").count();
assert.equal(pasos, 7);
await p.screenshot({ path: "capturas/t-salud.png" });
await b.close();
assert.deepEqual(errores, []);
console.log("tutorial de Salud: pruebas pasadas");
