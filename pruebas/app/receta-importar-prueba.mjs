import assert from "node:assert/strict";
import { chromium } from "playwright-core";
const b = await chromium.launch({ channel: "chrome", headless: true });
const errores = [];
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
await ctx.route(/\/api\//, (r) => r.fulfill({ json: { disponible: false, conectado: false, resultados: [] } }));
await ctx.addInitScript(() => { window.__plan = true; localStorage.setItem("comidas-bienvenida", "vista"); });
const p = await ctx.newPage();
p.on("pageerror", (e) => errores.push(e.message));
await p.goto("http://localhost:5199/?vista=ajustes");
await p.waitForTimeout(1200);
// Apple Salud: vinculado
const salud = await p.locator(".menu-ajustes button", { hasText: "Apple Salud" }).innerText();
console.log("menú:", salud.replace(/\n/g, " | "));
assert.ok(salud.includes("Vinculado"));
await p.locator(".menu-ajustes button", { hasText: "Apple Salud" }).click();
await p.waitForTimeout(600);
const estado = await p.locator(".estado-salud").innerText();
console.log("estado:", estado);
assert.ok(estado.includes("Vinculado") && estado.includes("último dato"));
await p.screenshot({ path: "capturas/salud-vinculado.png" });
await p.getByRole("button", { name: "Volver" }).click().catch(() => p.goBack());
await p.waitForTimeout(500);
// Receta desde texto
await p.locator(".menu-ajustes button", { hasText: "Mis recetas" }).click();
await p.waitForTimeout(400);
await p.getByRole("button", { name: "Nueva receta" }).click();
await p.waitForTimeout(500);
await p.getByRole("button", { name: /Importar foto o texto/ }).click();
await p.getByLabel("Texto del resumen").fill("Budín de limón\nRinde 10 porciones\nIngredientes\n- 250 g de harina leudante\n- 3 huevos\n- 200 g de azúcar\n- 100 ml de aceite\n- Ralladura de 1 limón\nPreparación\nMezclar y hornear");
await p.getByRole("button", { name: "Leer texto" }).click();
await p.waitForTimeout(600);
assert.equal(await p.getByLabel("Nombre de la receta").inputValue(), "Budín de limón");
assert.equal(await p.getByLabel("Porciones", { exact: true }).inputValue(), "10");
const nota = await p.locator(".editor-receta [role=status]").innerText();
console.log("nota:", nota);
assert.ok(nota.includes("Agregué 4 ingredientes") && nota.includes("Ralladura"));
assert.equal(await p.locator(".editor-receta .fila-item").count(), 4);
await p.getByRole("button", { name: "8", exact: true }).click();
assert.equal(await p.getByLabel("Porciones", { exact: true }).inputValue(), "8");
const resumen = await p.locator(".resumen-receta").innerText();
console.log("resumen:", resumen.replace(/\n/g, " | "));
await p.screenshot({ path: "capturas/receta-importada.png" });
await p.getByRole("button", { name: "Guardar receta" }).click();
await p.waitForTimeout(700);
const r = await p.evaluate(() => window.__db.recetas_propias.at(-1));
assert.equal(r.porciones, 8);
assert.equal(r.ingredientes.length, 4);
await b.close();
assert.deepEqual(errores, []);
console.log("receta importada y salud vinculada: pruebas pasadas");
