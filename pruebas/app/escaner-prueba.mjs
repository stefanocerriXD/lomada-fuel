import { chromium } from "playwright-core";
const b = await chromium.launch({ channel: "chrome", headless: true, args: ["--use-fake-device-for-media-stream", "--use-fake-ui-for-media-stream"] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2, permissions: ["camera"] });
await ctx.route(/\/api\//, (r) => r.fulfill({ json: { disponible: false, conectado: false, resultados: [] } }));
await ctx.addInitScript(() => localStorage.setItem("comidas-bienvenida", "vista"));
const p = await ctx.newPage();
const log = [];
p.on("console", (m) => log.push(m.type() + ": " + m.text()));
p.on("pageerror", (e) => log.push("ERR " + e.message));
await p.goto("http://localhost:5199");
await p.waitForTimeout(1500);
await p.keyboard.press("Escape");
await p.locator("[aria-label='Subir comida']").last().click();
await p.waitForTimeout(800);
const btn = p.getByRole("button", { name: /código|Código|Escanear/ }).first();
console.log("boton:", await btn.innerText().catch(() => "?"));
await btn.click();
await p.waitForTimeout(3500); await p.locator(".visor").scrollIntoViewIfNeeded();
console.log(await p.evaluate(() => { const v = document.querySelector(".visor video"); if (!v) return "sin video"; const r = v.getBoundingClientRect(); return { w: v.videoWidth, h: v.videoHeight, paused: v.paused, ready: v.readyState, box: [r.width, r.height], src: !!v.srcObject, attrs: [...v.attributes].map((a) => a.name) }; }));
await p.screenshot({ path: "capturas/escaner.png" });
console.log(log.filter((l) => !l.startsWith("log")).slice(0, 10));
await b.close();
