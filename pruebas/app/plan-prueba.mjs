import assert from "node:assert/strict";
import { chromium } from "playwright-core";
const b = await chromium.launch({ channel: "chrome", headless: true });
const errores = [];
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
await ctx.route(/\/api\//, (r) => r.fulfill({ json: { disponible: false, conectado: false, resultados: [] } }));
await ctx.addInitScript(() => { window.__plan = true; localStorage.setItem("comidas-bienvenida", "vista"); });
const p = await ctx.newPage();
p.on("pageerror", (e) => errores.push(e.message));
await p.goto("http://localhost:5199");
await p.waitForTimeout(1200);
await p.getByRole("button", { name: "Ajustes", exact: true }).locator("visible=true").first().click();
await p.waitForTimeout(500);
await p.getByRole("button", { name: /Tu perfil Nombre/ }).click();
await p.waitForTimeout(500);
const antes = await p.locator(".ajuste-texto strong").first().innerText();
console.log("antes:", antes);
await p.getByRole("button", { name: "Editar mi plan" }).click();
await p.waitForTimeout(500);
for (let i = 0; i < 3; i++) { await p.getByRole("button", { name: "Seguir" }).click(); await p.waitForTimeout(300); }
await p.getByRole("radio", { name: /Bulkear/ }).click();
await p.screenshot({ path: "capturas/plan-objetivo.png" });
await p.getByRole("button", { name: "Seguir" }).click();
await p.waitForTimeout(400);
const prote = async () => Number((await p.locator(".plan-datos li", { hasText: "Proteínas" }).innerText()).match(/(\d+) g/)[1]);
const equilibrado = await prote();
await p.getByRole("radio", { name: "Más proteína" }).click();
await p.waitForTimeout(200);
const mas = await prote();
console.log("proteína bulk equilibrado / más proteína:", equilibrado, mas);
assert.ok(mas > equilibrado);
await p.screenshot({ path: "capturas/plan-prioridad.png" });
await p.getByText("Poner mis macros a medida").click();
await p.waitForTimeout(200);
assert.equal(Number(await p.getByLabel("Proteínas (g)").inputValue()), mas, "arranca con los gramos sugeridos");
await p.getByLabel("Proteínas (g)").fill("210");
await p.getByLabel("Carbos (g)").fill("400");
await p.getByLabel("Grasas (g)").fill("80");
await p.waitForTimeout(200);
assert.ok((await p.locator(".plan-principal").innerText()).includes((210 * 4 + 400 * 4 + 80 * 9).toLocaleString("es-AR")));
await p.screenshot({ path: "capturas/plan-a-medida.png" });
await p.getByLabel("Grasas (g)").fill("2");
assert.equal(await p.getByRole("button", { name: "Guardar mi plan" }).isDisabled(), true, "no deja guardar valores fuera de rango");
await p.getByLabel("Grasas (g)").fill("80");
await p.getByRole("button", { name: "Guardar mi plan" }).click();
await p.waitForTimeout(800);
const fila = await p.evaluate(() => window.__db.perfiles_salud.find((x) => x.usuario_id === "u1"));
console.log("guardado:", { objetivo: fila.objetivo, prioridad: fila.prioridad, p: fila.proteinas_propias, c: fila.carbos_propios, g: fila.grasas_propias });
assert.deepEqual([fila.objetivo, fila.prioridad, fila.proteinas_propias, fila.carbos_propios, fila.grasas_propias], ["bulk", "proteina", 210, 400, 80]);
const meta = await p.evaluate(() => window.__db.perfiles.find((x) => x.id === "u1").meta_calorias);
assert.equal(meta, 210 * 4 + 400 * 4 + 80 * 9, "la meta sale de los macros");
const despues = await p.locator(".ajuste-texto strong").first().innerText();
console.log("después:", despues);
assert.ok(despues.includes("Bulkear") && despues.includes("a medida"));
await p.screenshot({ path: "capturas/plan-ajustes.png" });
await b.close();
assert.deepEqual(errores, []);
console.log("plan por objetivo: pruebas pasadas");
